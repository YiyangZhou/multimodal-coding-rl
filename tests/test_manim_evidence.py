from pathlib import Path

import pytest

from mmrl.manim_render import RuntimeUnavailable, check_runtime, final_artifacts


def test_partial_movie_does_not_make_failed_scene_executable(tmp_path):
    partial = tmp_path / "videos/answer/480p15/partial_movie_files/Scene/partial.mp4"
    partial.parent.mkdir(parents=True)
    partial.write_bytes(b"a complete intermediate fragment")
    assert final_artifacts(tmp_path) == []
    final = partial.parents[2] / "Scene.mp4"
    final.write_bytes(b"a final scene")
    assert final_artifacts(tmp_path) == [final]


def test_empty_and_external_artifacts_are_not_evidence(tmp_path):
    media = tmp_path / "media"
    images = media / "images/answer"
    images.mkdir(parents=True)
    (images / "empty.png").touch()
    external = tmp_path / "external.png"
    external.write_bytes(b"not generated by this render")
    (images / "link.png").symlink_to(external)
    assert final_artifacts(media) == []


def test_missing_interpreter_is_infrastructure_failure():
    with pytest.raises(RuntimeUnavailable, match="Missing renderer dependency"):
        check_runtime(str(Path("/no-such-manim-environment/python")))
